// Builds style.js from the shared design-system sheets (tokens + components) and the game layout.
// Edit design-system/*.css in step with the Dusk Isles UI design system; edit layout.css for the game only.
import fs from "fs";
const d = new URL(".", import.meta.url).pathname;
const css = ["design-system/tokens.css", "design-system/components.css", "layout.css"].map((f) => fs.readFileSync(d + f, "utf8")).join("\n");
fs.writeFileSync(d + "style.js", "// generated by build-style.mjs from design-system/tokens.css, design-system/components.css and layout.css\nexport default " + JSON.stringify(css) + ";\n");
